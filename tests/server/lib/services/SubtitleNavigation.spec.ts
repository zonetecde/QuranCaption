import { describe, expect, test } from 'vitest';
import {
	AssetClip,
	PredefinedSubtitleClip,
	SilenceClip,
	SubtitleClip
} from '$lib/classes/Clip.svelte';
import { QuranSubtitleClip } from '$lib/compatibility/QuranSubtitleClip.svelte';
import { getSubtitleVerseKeyLabel } from '$lib/services/SubtitleNavigation';

describe('getSubtitleVerseKeyLabel', () => {
	test('ignores clips without subtitle text, including silences generated by transcription', () => {
		expect(getSubtitleVerseKeyLabel(new SilenceClip(0, 1000))).toBe('');
		expect(getSubtitleVerseKeyLabel(new AssetClip(0, 1000, 42))).toBe('');
	});

	test('reads Quran annotations from Minbar subtitles', () => {
		expect(getSubtitleVerseKeyLabel(new SubtitleClip(1001, 2000, 'قال {{2:255:1-3}}'))).toBe(
			'2:255'
		);
		expect(
			getSubtitleVerseKeyLabel(new PredefinedSubtitleClip(1001, 2000, 'Other', '{{2:255}}'))
		).toBe('2:255');
	});

	test('preserves legacy Quran subtitle references', () => {
		const clip = new QuranSubtitleClip(0, 1000, 2, 255, 0, 0, 'Text', [], true, true);
		expect(getSubtitleVerseKeyLabel(clip)).toBe('2:255');
	});

	test('returns no reference for ordinary subtitles and absent clips', () => {
		expect(getSubtitleVerseKeyLabel(new SubtitleClip(0, 1000, 'Lecture text'))).toBe('');
		expect(getSubtitleVerseKeyLabel(null)).toBe('');
		expect(getSubtitleVerseKeyLabel(undefined)).toBe('');
	});
});
